// Проверка сообщения коммита. Запускается сама при `git commit` через хук
// .husky/commit-msg; хук ставится при `pnpm install` (скрипт prepare).
//
// ─── Формат ─────────────────────────────────────────────────────────────────
//
//   тип(область): описание
//
//   - тип — обязателен, из списка ниже;
//   - (область) — необязательна: часть проекта, например (args), (prompts);
//   - описание — со строчной буквы, без точки в конце, по-английски,
//     в повелительном наклонении: «add», «fix», а не «added», «fixes»;
//   - вся первая строка — не длиннее 100 символов;
//   - после первой строки — пустая строка и, если нужно, подробности.
//
// ─── Типы и что они делают с релизом ────────────────────────────────────────
//
//   feat      новая возможность        версия 0.1.0 → 0.2.0, в CHANGELOG
//   fix       исправление ошибки       версия 0.1.0 → 0.1.1, в CHANGELOG
//   perf      ускорение                версия 0.1.0 → 0.1.1, в CHANGELOG
//   revert    откат коммита            версия 0.1.0 → 0.1.1, в CHANGELOG
//   docs      документация             не меняет версию
//   refactor  переделка без изменения поведения
//   test      тесты
//   build     сборка, зависимости
//   ci        CI и workflow
//   chore     прочее обслуживание
//   style     форматирование кода
//
//   Ломающее изменение — `!` после типа: `feat!: drop --lang shortcut`.
//   Пока версия 0.x, оно поднимает минор (0.1.0 → 0.2.0), после 1.0 — мажор.
//
//   Как выбрать: заметит ли изменение тот, кто запускает генератор?
//   Заметит и это новое — feat; раньше было сломано — fix; не заметит —
//   refactor / docs / test / build / ci / chore.
//
// ─── Примеры ────────────────────────────────────────────────────────────────
//
//   ✓ feat: add --template flag
//   ✓ fix(args): reject empty --variant value
//   ✓ docs: describe release steps
//   ✗ Added a new flag          — нет типа
//   ✗ rework: tidy prompts      — неизвестный тип (нужен refactor)
//   ✗ feat: Add flag            — описание с заглавной буквы
//   ✗ fix: handle offline mode. — точка в конце
//
// ─── Если проверка мешает ───────────────────────────────────────────────────
//
//   git commit --no-verify -m "..."     пропустить проверку один раз (или -n)
//
//   Коммит с неправильным типом release-please молча пропустит: он не попадёт
//   в CHANGELOG и не поднимет версию. Обходить стоит только осознанно,
//   например для временного коммита, который потом будет переписан.
export default {
  extends: ['@commitlint/config-conventional'],
  rules: {
    // Длину строк в теле коммита не ограничиваем: IDE и генераторы сообщений
    // не переносят строки сами, а длинная ссылка в теле — обычное дело.
    // Первая строка по-прежнему не длиннее 100 символов.
    'body-max-line-length': [0], // 0 — правило выключено
  },
}
